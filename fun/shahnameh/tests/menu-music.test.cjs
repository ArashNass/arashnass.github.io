const assert = require('node:assert/strict');
const fs = require('node:fs');
const vm = require('node:vm');
const src = fs.readFileSync(require('node:path').join(__dirname, '../game.js'), 'utf8');
let attempts = 0, fades = 0;
const el = { paused: true, currentTime: 0, play() { attempts++; return Promise.resolve(); } };
const A = { cur: 'menu', ctx: { currentTime: 0 }, tracks: { menu: { el, g: { gain: { cancelScheduledValues() {}, setTargetAtTime() {} } } } } };
const context = { A, clearTimeout, isScore: () => false, MENU_SYNTH: false, track: () => A.tracks.menu, trackVol: () => 0.75, fadeOut() { fades++; } };
vm.createContext(context);
vm.runInContext(src.slice(src.indexOf('function setTrack(name)'), src.indexOf('// the menu theme:')), context);
context.setTrack('menu');
assert.equal(attempts, 1, 'retry the track rejected before user activation');
el.paused = false;
context.setTrack('menu');
assert.equal(attempts, 1, 'leave a playing track uninterrupted');
A.cur = null;
context.setTrack(null);
assert.equal(attempts, 1, 'silence stays silent');
const handlers = {};
const button = { querySelector: () => ({ textContent: '' }), setAttribute() {} };
let starts = 0;
const ui = { A: { ctx: { state: 'suspended', resume: () => Promise.resolve() }, tracks: { menu: { el } }, cur: 'menu', background: false }, SET: { music: 70 }, $: () => button, saveSet() {}, applySettings() {}, music() { starts++; }, setMuted() {}, document: { addEventListener(k, f) { handlers[k] = f; } }, setInterval() {} };
vm.createContext(ui);
vm.runInContext(src.slice(src.indexOf('function musicOn()'), src.indexOf("$('mapClose').onclick")), ui);
assert.equal(ui.musicPlaying(), false, 'suspended audio must not display Music on');
button.onclick();
assert.equal(ui.SET.music, 70, 'first music click must enable, not silence pending music');
assert.equal(starts, 1);
ui.A.ctx.state = 'running';
assert.equal(ui.musicPlaying(), true);
button.onclick();
assert.equal(ui.A.landingMusic, false, 'second click turns landing music off');
assert.equal(ui.SET.music, 70, 'landing toggle preserves gameplay volume');
handlers.pointerdown({ target: { closest: () => false } });
assert.equal(starts, 3, 'gesture may unlock audio without changing landing preference');
assert.equal(ui.A.landingMusic, false);
console.log('Landing music activation, blocked-track retry, honest status and saved off preference passed silently.');

const selections = [];
const routing = { A: { ctx: {}, landingMusic: false }, $: () => ({ classList: { contains: () => false } }), setTrack: name => selections.push(name) };
vm.createContext(routing);
vm.runInContext(src.slice(src.indexOf('function pickTrack()'), src.indexOf('const music = on')), routing);
routing.pickTrack();
assert.equal(selections.pop(), null, 'landing music defaults to silent');
routing.A.landingMusic = true;
routing.pickTrack();
assert.equal(selections.pop(), 'menu', 'explicit landing opt-in starts menu theme');
routing.A.landingMusic = false;
routing.$ = () => ({ classList: { contains: () => true } });
routing.pickTrack();
assert.equal(selections.pop(), 'menu', 'landing preference does not silence other screens');
